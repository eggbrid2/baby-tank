#!/usr/bin/env python3
"""Convert an image-generated face into a deterministic three-color LCD asset."""

from __future__ import annotations

import argparse
import hashlib
from pathlib import Path

from PIL import Image


WIDTH = 240
HEIGHT = 240
BLACK = (0, 0, 0)
CYAN = (0, 216, 200)
CREAM = (255, 239, 194)


def rgb565(color: tuple[int, int, int]) -> int:
    red, green, blue = color
    return ((red & 0xF8) << 8) | ((green & 0xFC) << 3) | (blue >> 3)


def quantize(pixel: tuple[int, int, int]) -> tuple[int, int, int]:
    red, green, blue = pixel
    if max(red, green, blue) < 56:
        return BLACK
    if red < 160 and green > 80:
        return CYAN
    return CREAM


def encode_runs(pixels: list[int]) -> list[tuple[int, int]]:
    runs: list[tuple[int, int]] = []
    current = pixels[0]
    length = 1
    for pixel in pixels[1:]:
        if pixel == current and length < 0xFFFF:
            length += 1
        else:
            runs.append((length, current))
            current = pixel
            length = 1
    runs.append((length, current))
    return runs


def write_header(path: Path, runs: list[tuple[int, int]], source_sha256: str) -> None:
    lines = [
        "#pragma once",
        "",
        "#include <stddef.h>",
        "#include <stdint.h>",
        "",
        "/* Generated by tools/convert_pet_face.py; do not edit by hand.",
        f" * Source SHA-256: {source_sha256}",
        " */",
        f"#define PET_FACE_WIDTH {WIDTH}",
        f"#define PET_FACE_HEIGHT {HEIGHT}",
        "",
        "typedef struct {",
        "    uint16_t length;",
        "    uint16_t color;",
        "} pet_face_run_t;",
        "",
        "static const pet_face_run_t PET_FACE_RUNS[] = {",
    ]
    for length, color in runs:
        lines.append(f"    {{{length}, 0x{color:04X}}},")
    lines.extend(
        [
            "};",
            "",
            "#define PET_FACE_RUN_COUNT (sizeof(PET_FACE_RUNS) / sizeof(PET_FACE_RUNS[0]))",
            "",
        ]
    )
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text("\n".join(lines), encoding="utf-8")


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("source", type=Path)
    parser.add_argument("preview", type=Path)
    parser.add_argument("header", type=Path)
    args = parser.parse_args()

    source_bytes = args.source.read_bytes()
    source_sha256 = hashlib.sha256(source_bytes).hexdigest()
    source = Image.open(args.source).convert("RGB")
    resized = source.resize((WIDTH, HEIGHT), Image.Resampling.LANCZOS)
    converted = Image.new("RGB", (WIDTH, HEIGHT))
    converted.putdata([quantize(pixel) for pixel in resized.get_flattened_data()])

    args.preview.parent.mkdir(parents=True, exist_ok=True)
    converted.save(args.preview, optimize=True)

    packed_pixels = [rgb565(pixel) for pixel in converted.get_flattened_data()]
    runs = encode_runs(packed_pixels)
    write_header(args.header, runs, source_sha256)

    raw_bytes = WIDTH * HEIGHT * 2
    rle_bytes = len(runs) * 4
    print(f"source_sha256={source_sha256}")
    print(f"pixels={WIDTH * HEIGHT} colors={len(set(packed_pixels))} runs={len(runs)}")
    print(f"raw_bytes={raw_bytes} rle_bytes={rle_bytes}")


if __name__ == "__main__":
    main()

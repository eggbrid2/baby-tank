#!/usr/bin/env python3
"""Build compact, transparent RGB565 food sprites for the 240 px LCD."""

from __future__ import annotations

import hashlib
from pathlib import Path

from PIL import Image


ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / "android/app/src/main/res/drawable-nodpi"
OUTPUT = ROOT / "firmware/head/main/food_sprites.inc"
SIZE = 64
TRANSPARENT = 0xFF
SPRITES = (
    ("strawberry", "food_strawberry.png", "BABY_TANK_EXPRESSION_STRAWBERRY"),
    ("apple", "food_apple.png", "BABY_TANK_EXPRESSION_APPLE"),
    ("banana", "food_banana.png", "BABY_TANK_EXPRESSION_BANANA"),
    ("cake", "food_cake.png", "BABY_TANK_EXPRESSION_CAKE"),
    ("cookie", "food_cookie.png", "BABY_TANK_EXPRESSION_COOKIE"),
    ("bread", "food_bread.png", "BABY_TANK_EXPRESSION_BREAD"),
    ("rice_ball", "food_rice_ball.png", "BABY_TANK_EXPRESSION_RICE_BALL"),
    ("ice_cream", "food_ice_cream.png", "BABY_TANK_EXPRESSION_ICE_CREAM"),
    ("milk", "drink_milk.png", "BABY_TANK_EXPRESSION_MILK"),
    ("juice", "drink_juice.png", "BABY_TANK_EXPRESSION_JUICE"),
    ("water", "drink_water.png", "BABY_TANK_EXPRESSION_WATER"),
    ("yogurt", "drink_yogurt.png", "BABY_TANK_EXPRESSION_YOGURT"),
    ("soy_milk", "drink_soy_milk.png", "BABY_TANK_EXPRESSION_SOY_MILK"),
    ("cocoa", "drink_cocoa.png", "BABY_TANK_EXPRESSION_COCOA"),
)


def rgb565(red: int, green: int, blue: int) -> int:
    return ((red & 0xF8) << 8) | ((green & 0xFC) << 3) | (blue >> 3)


def array_lines(values: list[int], width: int, formatter) -> list[str]:
    return [
        "    " + ", ".join(formatter(value) for value in values[offset : offset + width]) + ","
        for offset in range(0, len(values), width)
    ]


def convert(path: Path) -> tuple[list[int], list[int], str]:
    source_bytes = path.read_bytes()
    source_hash = hashlib.sha256(source_bytes).hexdigest()
    rgba = Image.open(path).convert("RGBA").resize(
        (SIZE, SIZE), Image.Resampling.LANCZOS
    )
    alpha = list(rgba.getchannel("A").get_flattened_data())
    black = Image.new("RGBA", rgba.size, (0, 0, 0, 255))
    black.alpha_composite(rgba)
    rgb = black.convert("RGB")
    quantized = rgb.quantize(colors=31, method=Image.Quantize.MEDIANCUT)
    indices = [
        TRANSPARENT if opacity < 18 else index
        for opacity, index in zip(
            alpha, quantized.get_flattened_data(), strict=True
        )
    ]
    palette_bytes = quantized.getpalette() or []
    palette = []
    for index in range(31):
        offset = index * 3
        palette.append(rgb565(*palette_bytes[offset : offset + 3]))
    palette.append(0)
    return indices, palette, source_hash


def main() -> None:
    lines = [
        "/* Generated by tools/generate-food-sprites.py; do not edit by hand. */",
        "#define BABY_TANK_FOOD_SPRITE_SIZE 64",
        "#define BABY_TANK_FOOD_TRANSPARENT 0xFFU",
        "",
        "typedef struct {",
        "    const uint8_t *pixels;",
        "    const uint16_t *palette;",
        "} baby_tank_food_sprite_t;",
        "",
    ]
    for name, filename, _ in SPRITES:
        indices, palette, source_hash = convert(SOURCE / filename)
        lines.extend(
            [
                f"/* {filename} SHA-256: {source_hash} */",
                f"static const uint16_t s_food_{name}_palette[32] = {{",
                *array_lines(palette, 8, lambda value: f"0x{value:04X}"),
                "};",
                f"static const uint8_t s_food_{name}_pixels[{SIZE * SIZE}] = {{",
                *array_lines(indices, 24, lambda value: f"0x{value:02X}"),
                "};",
                "",
                f"static const baby_tank_food_sprite_t s_food_{name} = {{",
                f"    .pixels = s_food_{name}_pixels,",
                f"    .palette = s_food_{name}_palette,",
                "};",
                "",
            ]
        )
    lines.extend(
        [
            "static const baby_tank_food_sprite_t *baby_tank_food_sprite_for_expression(",
            "    baby_tank_expression_t expression)",
            "{",
            "    switch (expression) {",
        ]
    )
    for name, _, expression in SPRITES:
        lines.append(f"    case {expression}: return &s_food_{name};")
    lines.extend(["    default: return NULL;", "    }", "}", ""])
    OUTPUT.write_text("\n".join(lines), encoding="utf-8")
    raw_bytes = len(SPRITES) * SIZE * SIZE
    palette_bytes = len(SPRITES) * 32 * 2
    print(
        f"sprites={len(SPRITES)} pixels={raw_bytes} "
        f"palette_bytes={palette_bytes} total_flash_bytes={raw_bytes + palette_bytes}"
    )


if __name__ == "__main__":
    main()
